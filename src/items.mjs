function shaped(id, pattern, key, count = 1) {
  return {
    'minecraft:recipe_shaped': {
      description: { identifier: `${NS}:${id}` },
      tags: ['crafting_table'],
      pattern,
      key: Object.fromEntries(Object.entries(key).map(([k, v]) => [k, { item: `minecraft:${v}` }])),
      result: { item: `${NS}:${id}`, count },
      unlock: [{ item: `minecraft:${Object.values(key)[0]}` }],
    },
  };
}

function shapeless(id, ingredients, count = 1) {
  return {
    'minecraft:recipe_shapeless': {
      description: { identifier: `${NS}:${id}` },
      tags: ['crafting_table'],
      ingredients: ingredients.map((i) => ({ item: i.includes(':') ? i : `minecraft:${i}` })),
      result: { item: `${NS}:${id}`, count },
      unlock: [{ item: `minecraft:${ingredients[0]}` }],
    },
  };
}

export function buildItem(item) {
  const components = {
    'minecraft:icon': `${NS}_${item.id}`,
    'minecraft:display_name': { value: `item.${NS}:${item.id}.name` },
    'minecraft:max_stack_size': item.stack ?? 64,
    ...(item.components ?? {}),
  };
  return {
    format_version: '1.21.120',
    'minecraft:item': {
      description: { identifier: `${NS}:${item.id}`, menu_category: { category: item.category ?? 'items' } },
      components,
    },
  };
}
